#!/usr/bin/env python3
"""Regenerate ``engine/opening_lines.py`` from the chess-openings dataset.

The engine's opening book is built from the *chess-openings* collection
(https://github.com/niklasf/chess-openings, CC0 / public domain), which lists
ECO codes, opening names and the moves of every named line.

Usage
-----
Download ``a.tsv`` … ``e.tsv`` into a directory, then::

    python3 tools/build_opening_lines.py /path/to/tsv/folder

The generated file stores one ``(eco, name, "move moves moves")`` tuple per
line, sorted by ECO code.  ``engine/book.py`` replays those lines onto a board
when it starts, so nothing here is trusted blindly: an illegal line would be
rejected loudly at import time.
"""

from __future__ import annotations

import argparse
import io
import textwrap
from pathlib import Path

import chess
import chess.pgn

HEADER = '''"""Opening theory: ECO code, name and moves of every named opening line.

Generated by ``tools/build_opening_lines.py`` from the chess-openings dataset
(https://github.com/niklasf/chess-openings, public domain / CC0).  Do not edit
by hand — rerun the generator instead.

Each entry is ``(eco, name, "Nf3 d5 c4 ...")`` with the moves in SAN.
"""

from __future__ import annotations

#: ``(eco, name, san moves)`` for {count} named lines, longest first.
OPENING_LINES: tuple[tuple[str, str, str], ...] = (
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="folder containing a.tsv … e.tsv")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "engine" / "opening_lines.py",
    )
    parser.add_argument("--min-plies", type=int, default=2, help="skip shorter lines")
    parser.add_argument("--max-plies", type=int, default=24, help="truncate longer lines")
    args = parser.parse_args()

    entries: list[tuple[str, str, str]] = []
    seen: set[tuple[str, str, tuple[str, ...]]] = set()
    skipped = 0

    for letter in "abcde":
        path = args.source / f"{letter}.tsv"
        if not path.exists():
            parser.error(f"missing {path}")
        rows = path.read_text(encoding="utf-8").splitlines()
        header = rows[0].split("\t")
        for row in rows[1:]:
            if not row.strip():
                continue
            parts = row.split("\t")
            if len(parts) < len(header):
                continue
            record = dict(zip(header, parts))
            pgn = record.get("pgn", "").strip()
            name = record.get("name", "").strip()
            eco = record.get("eco", "").strip()
            if not pgn or not name:
                continue
            game = chess.pgn.read_game(io.StringIO(pgn))
            if game is None:
                skipped += 1
                continue
            board = game.board()
            moves: list[str] = []
            legal = True
            for move in game.mainline_moves():
                if move not in board.legal_moves:
                    legal = False
                    break
                moves.append(board.san(move))
                board.push(move)
            if not legal or len(moves) < args.min_plies:
                skipped += 1
                continue
            moves = moves[: args.max_plies]
            key = (eco, name, tuple(moves))
            if key in seen:
                continue
            seen.add(key)
            entries.append((eco, name, " ".join(moves)))

    # Longest (most deeply documented) lines first, then alphabetical, so the
    # book consistently prefers main theory over one-move sidelines.
    entries.sort(key=lambda item: (-len(item[2].split()), item[0], item[1]))

    lines = [HEADER.format(count=len(entries))]
    for eco, name, moves in entries:
        text = textwrap.shorten(name, width=88, placeholder="…")
        lines.append(f'    ({eco!r}, {text!r},\n     {moves!r}),\n')
    lines.append(")\n")
    args.output.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {len(entries)} lines to {args.output} (skipped {skipped})")
    print(f"file size: {args.output.stat().st_size / 1024:.0f} KiB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
